/**
 * Строка оглавления («Содержание») с отточием и номером страницы в одной строке без переносов
 */
function tocEntry(title, pageNum, isSub = false) {
  return new Paragraph({
    alignment: AlignmentType.LEFT,
    indent: isSub ? { left: 425 } : undefined,
    spacing: { before: 0, after: 80, line: 240 },
    tabStops: [
      {
        type: TabStopType.RIGHT,
        position: TOC_RIGHT_TAB_POS,
        leader: LeaderType.DOT
      }
    ],
    children: [
      new TextRun({
        text: title,
        font: FONT_FAMILY,
        size: FONT_SIZE
      }),
      new TextRun({
        text: `\t${pageNum}`,
        font: FONT_FAMILY,
        size: FONT_SIZE
      })
    ]
  });
}

function figureBlock(imageFilename, figNumber, captionText, widthPx = 560, heightPx = 270) {
  const imgPath = path.join(ASSETS_DIR, imageFilename);
  const imgBuffer = fs.readFileSync(imgPath);

  return [
    emptyLine(),
    new Paragraph({
      alignment: AlignmentType.CENTER,
      keepNext: true,
      spacing: { before: 0, after: 80, line: 240 },
      children: [
        new ImageRun({
          data: imgBuffer,
          transformation: {
            width: widthPx,
            height: heightPx
          }
        })
      ]
    }),
    new Paragraph({
      alignment: AlignmentType.CENTER,
      spacing: { before: 0, after: 0, line: 240 },
      children: [
        new TextRun({
          text: normalizeDashes(`Рисунок ${figNumber} - ${captionText}`),
          font: FONT_FAMILY,
          size: FONT_SIZE
        })
      ]
    }),
    emptyLine()
  ];
}

function tableBlock(tableNumber, titleText, headers, rows, colWidthsPercent = []) {
  const borderSpec = {
    style: BorderStyle.SINGLE,
    size: 6,
    color: '000000'
  };
  const cellBorders = {
    top: borderSpec,
    bottom: borderSpec,
    left: borderSpec,
    right: borderSpec
  };

  const headerRow = new TableRow({
    tableHeader: true,
    cantSplit: true,
    children: headers.map(
      (h, idx) =>
        new TableCell({
          borders: cellBorders,
          width: colWidthsPercent[idx]
            ? { size: colWidthsPercent[idx], type: WidthType.PERCENTAGE }
            : undefined,
          children: [
            new Paragraph({
              alignment: AlignmentType.CENTER,
              spacing: { before: 30, after: 30, line: 240 },
              children: [
                new TextRun({
                  text: normalizeDashes(h),
                  font: FONT_FAMILY,
                  size: FONT_SIZE,
                  bold: true
                })
              ]
            })
          ]
        })
    )
  });

  const dataRows = rows.map(
    (r) =>
      new TableRow({
        cantSplit: true,
        children: r.map(
          (cellText, idx) =>
            new TableCell({
              borders: cellBorders,
              width: colWidthsPercent[idx]
                ? { size: colWidthsPercent[idx], type: WidthType.PERCENTAGE }
                : undefined,
              children: [
                new Paragraph({
                  alignment: AlignmentType.LEFT,
                  spacing: { before: 30, after: 30, line: 240 },
                  children: [
                    new TextRun({
                      text: normalizeDashes(cellText),
                      font: FONT_FAMILY,
                      size: FONT_SIZE
                    })
                  ]
                })
              ]
            })
        )
      })
  );

  return [
    emptyLine(),
    new Paragraph({
      alignment: AlignmentType.LEFT,
      keepNext: true,
      spacing: { before: 0, after: 60, line: 240 },
      children: [
        new TextRun({
          text: normalizeDashes(`Таблица ${tableNumber} - ${titleText}`),
          font: FONT_FAMILY,
          size: FONT_SIZE
        })
      ]
    }),
    new Table({
      width: { size: 100, type: WidthType.PERCENTAGE },
      rows: [headerRow, ...dataRows]
    }),
    emptyLine()
  ];
}

